insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('varta-videos','varta-videos',false,52428800,array['video/mp4','video/webm','video/quicktime'])
on conflict (id) do update set public=excluded.public,file_size_limit=excluded.file_size_limit,allowed_mime_types=excluded.allowed_mime_types;
create table if not exists public.video_posts (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 title text not null check (char_length(btrim(title)) between 5 and 120),
 description text not null check (char_length(btrim(description)) between 20 and 2000),
 topic text not null check (topic in ('Science & Technology','Indian Knowledge','Sound & NADA','Culture & Nature','World Affairs','Citizen Reports')),
 object_path text not null unique,
 source_url text check (source_url is null or source_url ~ '^https?://'),
 status text not null default 'pending' check (status in ('pending','published','rejected')),
 created_at timestamptz not null default now(),
 reviewed_at timestamptz,
 reviewed_by uuid references auth.users(id) on delete set null
);
create index if not exists video_posts_status_created_at_idx on public.video_posts(status,created_at desc);
create index if not exists video_posts_user_created_at_idx on public.video_posts(user_id,created_at desc);
create index if not exists video_posts_reviewed_by_idx on public.video_posts(reviewed_by);
alter table public.video_posts enable row level security;
drop policy if exists "Published videos are visible to everyone" on public.video_posts;
drop policy if exists "Owners and moderators can view own or review videos" on public.video_posts;
drop policy if exists "Published videos or authorized submissions are visible" on public.video_posts;
create policy "Published videos or authorized submissions are visible" on public.video_posts for select to anon,authenticated using (
 status='published' or ((select auth.uid()) is not null and (user_id=(select auth.uid()) or exists(select 1 from public.moderators m where m.user_id=(select auth.uid()))))
);
drop policy if exists "Members can submit their own pending videos" on public.video_posts;
create policy "Members can submit their own pending videos" on public.video_posts for insert to authenticated with check (user_id=(select auth.uid()) and status='pending' and object_path like (select auth.uid())::text || '/%');
drop policy if exists "Owners can delete their own pending or rejected videos" on public.video_posts;
create policy "Owners can delete their own pending or rejected videos" on public.video_posts for delete to authenticated using (user_id=(select auth.uid()) and status in ('pending','rejected'));
drop policy if exists "Moderators can review videos" on public.video_posts;
create policy "Moderators can review videos" on public.video_posts for update to authenticated using (exists(select 1 from public.moderators m where m.user_id=(select auth.uid()))) with check (exists(select 1 from public.moderators m where m.user_id=(select auth.uid())));

drop policy if exists "Published or authorized video objects can be read" on storage.objects;
create policy "Published or authorized video objects can be read" on storage.objects for select to anon,authenticated using (
 bucket_id='varta-videos' and exists (
  select 1 from public.video_posts vp where vp.object_path=storage.objects.name and
   (vp.status='published' or vp.user_id=(select auth.uid()) or exists(select 1 from public.moderators m where m.user_id=(select auth.uid())))
 )
);

drop policy if exists "Authenticated members can upload video to own folder" on storage.objects;
create policy "Authenticated members can upload video to own folder" on storage.objects for insert to authenticated with check (bucket_id='varta-videos' and (storage.foldername(name))[1]=(select auth.uid())::text);
drop policy if exists "Authenticated members can update video in own folder" on storage.objects;
create policy "Authenticated members can update video in own folder" on storage.objects for update to authenticated using (bucket_id='varta-videos' and (storage.foldername(name))[1]=(select auth.uid())::text) with check (bucket_id='varta-videos' and (storage.foldername(name))[1]=(select auth.uid())::text);
drop policy if exists "Authenticated members can delete video in own folder" on storage.objects;
create policy "Authenticated members can delete video in own folder" on storage.objects for delete to authenticated using (bucket_id='varta-videos' and (storage.foldername(name))[1]=(select auth.uid())::text);
grant select on public.video_posts to anon,authenticated;
grant insert,delete,update on public.video_posts to authenticated;
